-- ============================================================================
-- Model Proxy Minimal Request Context Telemetry - Fresh Start Migration (Supabase)
-- Date: 2026-02-03
--
-- Goal:
--   Replace all existing model-proxy telemetry tables with a minimal schema focused on
--   request context condensation analysis.
--
-- This migration:
--   - Drops legacy llm_* objects
--   - Drops all existing model_proxy_* objects (tables/views/materialized views/functions)
--   - Creates new minimal model_proxy_* tables:
--       * model_proxy_requests
--       * model_proxy_request_contexts
--
-- IMPORTANT:
--   This migration DOES NOT preserve historical data.
--   All existing data in dropped objects will be permanently lost.
-- ============================================================================

BEGIN;

-- Required for gen_random_uuid()
CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- ============================================================================
-- STEP 0: Drop legacy llm_* objects (if present)
-- ============================================================================

DROP TABLE IF EXISTS public.llm_usage_events CASCADE;
DROP TABLE IF EXISTS public.llm_http_payloads CASCADE;
DROP TABLE IF EXISTS public.llm_raw_prompts CASCADE;

-- llm_usage_daily may have been created as a view/materialized view/table in older versions.
DO $$
DECLARE
    obj regclass;
    kind "char";
BEGIN
    obj := to_regclass('public.llm_usage_daily');
    IF obj IS NULL THEN
        RETURN;
    END IF;

    SELECT c.relkind INTO kind
    FROM pg_class c
    WHERE c.oid = obj;

    IF kind = 'm' THEN
        EXECUTE 'DROP MATERIALIZED VIEW public.llm_usage_daily CASCADE';
    ELSIF kind = 'v' THEN
        EXECUTE 'DROP VIEW public.llm_usage_daily CASCADE';
    ELSE
        EXECUTE 'DROP TABLE public.llm_usage_daily CASCADE';
    END IF;
END $$;

DROP TABLE IF EXISTS public.llm_usage_events_backup CASCADE;
DROP TABLE IF EXISTS public.llm_http_payloads_backup CASCADE;

-- ============================================================================
-- STEP 1: Drop ALL existing model_proxy_* objects (fresh start)
-- ============================================================================

-- Drop known views/materialized views first (CASCADE handles dependencies, but be explicit).
DROP MATERIALIZED VIEW IF EXISTS public.model_proxy_daily_stats CASCADE;
DROP VIEW IF EXISTS public.model_proxy_cost_summary CASCADE;
DROP VIEW IF EXISTS public.model_proxy_hourly_usage CASCADE;
DROP VIEW IF EXISTS public.model_proxy_performance CASCADE;

-- Drop known functions/triggers used by prior schemas
DROP FUNCTION IF EXISTS public.refresh_model_proxy_daily_stats() CASCADE;
DROP FUNCTION IF EXISTS public.model_proxy_update_updated_at_column() CASCADE;
DROP FUNCTION IF EXISTS public.model_proxy_get_pricing(VARCHAR) CASCADE;
DROP FUNCTION IF EXISTS public.model_proxy_calculate_cost(INTEGER, INTEGER, VARCHAR) CASCADE;

-- Drop known tables from prior migrations (CASCADE to remove FKs/triggers)
DROP TABLE IF EXISTS public.model_proxy_tool_executions CASCADE;
DROP TABLE IF EXISTS public.model_proxy_api_tools CASCADE;
DROP TABLE IF EXISTS public.model_proxy_api_messages CASCADE;
DROP TABLE IF EXISTS public.model_proxy_api_requests CASCADE;
DROP TABLE IF EXISTS public.model_proxy_pricing CASCADE;

DROP TABLE IF EXISTS public.model_proxy_raw_prompts CASCADE;
DROP TABLE IF EXISTS public.model_proxy_payloads CASCADE;
DROP TABLE IF EXISTS public.model_proxy_requests CASCADE;

-- ============================================================================
-- STEP 2: Create minimal request table
-- ============================================================================

CREATE TABLE public.model_proxy_requests (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    -- Stable request identifier used by the application (opaque string, not necessarily UUID)
    request_id TEXT UNIQUE NOT NULL,

    -- Dimensions
    app_id VARCHAR(255),
    provider VARCHAR(100) NOT NULL,
    model VARCHAR(255) NOT NULL,

    -- Timing / status
    request_timestamp TIMESTAMPTZ DEFAULT NOW(),
    response_timestamp TIMESTAMPTZ,
    latency_ms INTEGER,
    status_code INTEGER,
    error_message TEXT,

    -- Token counts (as requested)
    request_token_count INTEGER,
    response_token_count INTEGER,

    -- Payloads (as requested)
    request_payload JSONB NOT NULL,
    response_payload JSONB,

    -- Optional: lightweight metadata for analysis/debugging without schema churn
    metadata JSONB DEFAULT '{}'::jsonb,

    created_at TIMESTAMPTZ DEFAULT NOW()
);

COMMENT ON TABLE public.model_proxy_requests IS
    'Minimal per-request telemetry for model-proxy. Stores request/response payloads and token counts.';

COMMENT ON COLUMN public.model_proxy_requests.request_id IS 'Opaque request id generated by model-proxy (used for correlation).';
COMMENT ON COLUMN public.model_proxy_requests.request_payload IS 'Outbound payload sent to upstream provider (privacy sensitive).';
COMMENT ON COLUMN public.model_proxy_requests.response_payload IS 'Final response payload returned by upstream provider (privacy sensitive).';
COMMENT ON COLUMN public.model_proxy_requests.request_token_count IS 'Token count for the request prompt/context (best-effort).';
COMMENT ON COLUMN public.model_proxy_requests.response_token_count IS 'Token count for the response (best-effort).';

-- ============================================================================
-- STEP 3: Create request context table (raw + condensed)
-- ============================================================================

CREATE TABLE public.model_proxy_request_contexts (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    -- Link to request
    request_id TEXT NOT NULL REFERENCES public.model_proxy_requests(request_id) ON DELETE CASCADE,

    -- Contexts (as requested)
    raw_request_context TEXT,
    condensed_request_context TEXT,

    -- Optional: store condensation provenance + metrics for analysis
    condensation_method VARCHAR(100),
    condensation_version VARCHAR(50),
    condensation_trigger VARCHAR(100),

    raw_context_chars INTEGER,
    condensed_context_chars INTEGER,

    raw_context_token_count INTEGER,
    condensed_context_token_count INTEGER,

    tokens_saved INTEGER GENERATED ALWAYS AS (
        COALESCE(raw_context_token_count, 0) - COALESCE(condensed_context_token_count, 0)
    ) STORED,

    created_at TIMESTAMPTZ DEFAULT NOW()
);

COMMENT ON TABLE public.model_proxy_request_contexts IS
    'Stores raw vs condensed request context for condensation effectiveness analysis.';

COMMENT ON COLUMN public.model_proxy_request_contexts.raw_request_context IS
    'Canonical raw context (e.g., messages JSON or system+messages text) before condensation.';
COMMENT ON COLUMN public.model_proxy_request_contexts.condensed_request_context IS
    'Condensed context actually used (or intended to be used) for the request.';

-- ============================================================================
-- STEP 4: Indexes for analysis queries
-- ============================================================================

CREATE INDEX IF NOT EXISTS idx_mpr_time
    ON public.model_proxy_requests(request_timestamp DESC);

CREATE INDEX IF NOT EXISTS idx_mpr_app_time
    ON public.model_proxy_requests(app_id, request_timestamp DESC);

CREATE INDEX IF NOT EXISTS idx_mpr_provider_model_time
    ON public.model_proxy_requests(provider, model, request_timestamp DESC);

CREATE INDEX IF NOT EXISTS idx_mpr_status_errors
    ON public.model_proxy_requests(status_code)
    WHERE status_code >= 400;

CREATE INDEX IF NOT EXISTS idx_mpr_request_id
    ON public.model_proxy_requests(request_id);

CREATE INDEX IF NOT EXISTS idx_mprc_request_id
    ON public.model_proxy_request_contexts(request_id);

-- ============================================================================
-- STEP 5: Row Level Security (match prior pattern: authenticated read, service_role full)
-- ============================================================================

ALTER TABLE public.model_proxy_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.model_proxy_request_contexts ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow authenticated read access" ON public.model_proxy_requests
    FOR SELECT TO authenticated USING (true);

CREATE POLICY "Allow authenticated read access" ON public.model_proxy_request_contexts
    FOR SELECT TO authenticated USING (true);

CREATE POLICY "Allow service role full access" ON public.model_proxy_requests
    FOR ALL TO service_role USING (true);

CREATE POLICY "Allow service role full access" ON public.model_proxy_request_contexts
    FOR ALL TO service_role USING (true);

-- ============================================================================
-- STEP 6: Verify migration
-- ============================================================================

DO $$
DECLARE
    requests_count INTEGER;
    contexts_count INTEGER;
BEGIN
    SELECT COUNT(*) INTO requests_count
    FROM pg_tables
    WHERE schemaname = 'public'
      AND tablename = 'model_proxy_requests';

    SELECT COUNT(*) INTO contexts_count
    FROM pg_tables
    WHERE schemaname = 'public'
      AND tablename = 'model_proxy_request_contexts';

    IF requests_count = 0 THEN
        RAISE EXCEPTION 'Migration failed: model_proxy_requests table not found';
    END IF;

    IF contexts_count = 0 THEN
        RAISE EXCEPTION 'Migration failed: model_proxy_request_contexts table not found';
    END IF;

    RAISE NOTICE '✓ Migration verification passed';
    RAISE NOTICE '✓ model_proxy_requests table created';
    RAISE NOTICE '✓ model_proxy_request_contexts table created';
END $$;

COMMIT;

-- ============================================================================
-- MIGRATION COMPLETE
-- ============================================================================
